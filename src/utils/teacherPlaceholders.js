const DAY_KEYS = ['domingo', 'lunes', 'martes', 'miercoles', 'jueves', 'viernes', 'sabado'];

/**
 * Obtiene un placeholder dinámico contextual según el día exacto de la semana
 * y la hora de Bogotá, Colombia (UTC-5).
 * @param {string} fullName - Nombre completo del usuario / docente.
 * @returns {string}
 */
export function getTeacherDynamicPlaceholder(fullName) {
  const firstName = (fullName || 'Gina').trim().split(' ')[0];

  let hour = 0;
  let minute = 0;
  let dayIdx = 0; // 0=Sun, 1=Mon, ..., 6=Sat

  try {
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone: 'America/Bogota',
      hour12: false,
      hour: 'numeric',
      minute: 'numeric',
      weekday: 'short'
    });
    const parts = formatter.formatToParts(new Date());
    const dayMap = { sun: 0, mon: 1, tue: 2, wed: 3, thu: 4, fri: 5, sat: 6 };
    parts.forEach(p => {
      if (p.type === 'hour') hour = parseInt(p.value, 10);
      if (p.type === 'minute') minute = parseInt(p.value, 10);
      if (p.type === 'weekday') dayIdx = dayMap[p.value.toLowerCase()] ?? 0;
    });
  } catch (e) {
    const now = new Date();
    hour = now.getHours();
    minute = now.getMinutes();
    dayIdx = now.getDay();
  }

  if (hour === 24) hour = 0;

  const dayKey = DAY_KEYS[dayIdx] || 'lunes';
  const dayData = MESSAGES_BY_DAY[dayKey] || MESSAGES_BY_DAY.lunes;

  // Determinar la franja horaria según la hora de Bogotá
  const isLateNight = (hour === 0 && minute >= 30) || (hour >= 1 && hour < 6);
  const isMorning = hour >= 6 && hour < 12;
  const isAfternoon = hour >= 12 && hour < 19;

  let slotData = dayData.noche;
  if (isLateNight) {
    slotData = dayData.madrugada;
  } else if (isMorning) {
    slotData = dayData.manana;
  } else if (isAfternoon) {
    slotData = dayData.tarde;
  }

  // 60% probabilidad de divertido / 40% normal
  const isFunny = Math.random() < 0.6;
  const pool = isFunny ? slotData.funny : slotData.normal;

  const randomIndex = Math.floor(Math.random() * pool.length);
  const template = pool[randomIndex] || "¿Qué deseas asignar o publicar hoy, {nombre}?";
  return template.replace(/\{nombre\}/g, firstName);
}
